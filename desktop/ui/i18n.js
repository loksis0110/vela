let LANG = "ru";
let pluralRules = new Intl.PluralRules("ru");
let i18nApplied = false;

function t(key, vars) {
  let v = (I18N[LANG] && I18N[LANG][key]);
  if (v === undefined) v = I18N.ru[key];
  if (v === undefined) return key;
  if (Array.isArray(v)) {
    const n = vars && typeof vars.n === "number" ? vars.n : 0;
    const form = pluralRules.select(n);
    v = LANG === "ru"
      ? v[form === "one" ? 0 : form === "few" ? 1 : 2] || v[v.length - 1]
      : v[form === "one" ? 0 : 1] || v[v.length - 1];
  }
  if (!vars) return v;
  return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-alt]").forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
}

// setLang switches the language; reports whether it changed.
function setLang(lang) {
  lang = lang === "en" ? "en" : "ru";
  if (lang === LANG && i18nApplied) return false;
  i18nApplied = true;
  LANG = lang;
  pluralRules = new Intl.PluralRules(lang);
  document.documentElement.lang = lang;
  applyI18n();
  return true;
}

